"""Run: uv run test_slicing.py  — 3MF carries the flat config; orientation finds the flat side.
With PRUSA_SLICER=<binary> it also slices the 3MF with an empty datadir, as server-slicing does."""
import os, subprocess, tempfile, zipfile
from pathlib import Path

import numpy as np
import trimesh

tmp = Path(tempfile.mkdtemp())
os.environ["PROFILES_BACKUP_DIR"] = str(tmp / "backups")
import slicing as S

for d in ("vendor", "printer", "print", "filament"):
    (tmp / d).mkdir()
(tmp / "vendor/Acme.ini").write_text(
    "[printer:*common*]\nbed_shape = 0x0,250x0,250x210,0x210\nnozzle_diameter = 0.4\n"
    "[printer:Acme 0.4]\ninherits = *common*\nprinter_model = ACME\n"
    "[print:0.20mm Acme]\nlayer_height = 0.2\ncompatible_printers_condition = acme\n"
    "[filament:Generic PETG]\ntemperature = 240\nbed_temperature_extruder = 0\ncompatible_printers_condition = acme\n")
(tmp / "printer/My Acme.ini").write_text("inherits = Acme 0.4\nbed_shape = 0x0,250x0,250x210,0x210\nnozzle_diameter = 0.4\n")
(tmp / "print/My 0.2.ini").write_text("inherits = 0.20mm Acme\nlayer_height = 0.2\nperimeters = 3\n")
(tmp / "filament/My PETG.ini").write_text("inherits = Generic PETG\ntemperature = 245\n")

# Flat config: layering, overrides, preset ids, bookkeeping and crash keys gone.
cfg = S.flat_config("My Acme", "My 0.2", "My PETG", {"perimeters": "4"}, root=tmp)
assert cfg["temperature"] == "245" and cfg["layer_height"] == "0.2" and cfg["perimeters"] == "4", cfg
assert cfg["printer_settings_id"] == "My Acme" and cfg["filament_settings_id"] == "My PETG"
assert not (S.DROP_KEYS | S.CRASH_KEYS) & cfg.keys(), cfg.keys()

# L-shaped bracket lying on its side: the best candidate has a large flat face down.
plate = trimesh.creation.box([60, 40, 4]); wall = trimesh.creation.box([4, 40, 30])
wall.apply_translation([-28, 0, 17])
lshape = trimesh.util.concatenate([plate, wall])
lshape.apply_transform(trimesh.transformations.rotation_matrix(np.pi / 2, [1, 0, 0]))  # stood up badly
stl = tmp / "bracket.stl"; lshape.export(stl)
info = S.inspect(stl)
assert info["triangles"] == 24, info
cands = S.orient_candidates(stl)
assert cands[0]["label"] == "as loaded" and len(cands) >= 2, cands
best = max(cands, key=lambda c: c["bed_contact_mm2"])
assert best["bed_contact_mm2"] >= 2000, best  # 60x40 plate face down

# 3MF: rotated, on the bed, centred, config embedded.
out = tmp / "bracket.3mf"
res = S.build_3mf(stl, out, "My Acme", "My 0.2", "My PETG", {"perimeters": "4"}, best["rotation"], root=tmp)
with zipfile.ZipFile(out) as z:
    names = set(z.namelist()); conf = z.read("Metadata/Slic3r_PE.config").decode()
    model = z.read("3D/3dmodel.model").decode()
assert {"[Content_Types].xml", "_rels/.rels", "3D/3dmodel.model", "Metadata/Slic3r_PE.config"} <= names
assert conf.startswith("; generated by PrusaSlicer 2.9.7") and 'name="Application">PrusaSlicer-2.9.7<' in model
assert "; temperature = 245\n" in conf and "; perimeters = 4\n" in conf and "inherits" not in conf
zs = [float(s.split('"')[0]) for s in model.split(' z="')[1:]]
assert abs(min(zs)) < 1e-6, min(zs)  # lies on the bed
assert abs(res["size_mm"][2] - best["height_mm"]) < 0.01, (res, best)

ps = os.environ.get("PRUSA_SLICER")
if ps:  # the real thing: empty datadir, settings only from the project
    g = tmp / "bracket.gcode"
    subprocess.run([*ps.split(), "--datadir", str(tmp / "empty"), "--export-gcode", "-o", str(g), str(out)], check=True)
    text = g.read_text(errors="replace")
    assert "; perimeters = 4" in text and "; temperature = 245" in text, "project settings not used"
    print("sliced:", g.stat().st_size, "bytes")
print("ok")
